const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const requestSource = fs.readFileSync(path.join(root, 'api', 'request.uts'), 'utf8')
const configSource = fs.readFileSync(path.join(root, 'api', 'config.uts'), 'utf8')
const authSource = fs.readFileSync(path.join(root, 'api', 'auth.uts'), 'utf8')
const appSource = fs.readFileSync(path.join(root, 'App.uvue'), 'utf8')

assert.match(requestSource, /uni\.request\s*\(/, 'real requests must use uni.request')
assert.doesNotMatch(requestSource, /uniCloud\.callFunction|realCloudRequest/, 'request transport must not use uniCloud')
assert.doesNotMatch(requestSource, /API_CONFIG\.useHttp/, 'FastAPI transport must not depend on a useHttp switch')
assert.doesNotMatch(configSource, /\bcloudFunction\s*:|\buseHttp\s*:/, 'API config must not expose the removed uniCloud transport')

assert.match(requestSource, /buildApiUrl\(urlPath\)/, 'request transport must use the shared URL builder')
assert.match(requestSource, /getAccessToken\(\)/, 'request transport must use the shared token reader')
assert.match(requestSource, /if \(options\.skipAuth != true\)/, 'public authentication requests must support skipAuth')
assert.match(requestSource, /method == 'GET' \|\| method == 'DELETE'/, 'GET and DELETE parameters must be serialized explicitly')
assert.match(requestSource, /encodeURIComponent/, 'query parameters must be encoded')
assert.match(requestSource, /status == 204/, '204 responses must return an explicit empty success result')
assert.match(requestSource, /status == 401[\s\S]*clearAuthTokens\(\)/, '401 responses must clear stale authentication')
assert.match(requestSource, /fail:\s*\(err: any\) => \{[\s\S]*?resolve\(\{[\s\S]*?success: false/, 'transport failures must resolve the standard failure shape')
assert.match(requestSource, /err\.errMsg/, 'transport failures must preserve the UniApp error message')
assert.doesNotMatch(requestSource, /\[HTTP Request\][^\n]*options\.data/, 'real request logs must not include request payloads')
assert.match(requestSource, /options\.mockData\.success === false/, 'the temporary Mock branch must preserve failure responses')

assert.match(configSource, /export const FASTAPI_AUTO_ENTER_COMMUNITY = false/, 'automatic community entry must be opt-in')
assert.match(configSource, /export const FASTAPI_DEV_ACCESS_TOKEN = ''/, 'the repository must not contain a development access token')
assert.match(configSource, /export const FASTAPI_DEV_USER_ID = 0/, 'the repository must not assume a backend test user')
assert.match(appSource, /FASTAPI_AUTO_ENTER_COMMUNITY != true/, 'startup must check the automatic entry switch')
assert.match(appSource, /FASTAPI_DEV_ACCESS_TOKEN == ''/, 'startup must reject an empty development token')
assert.match(appSource, /FASTAPI_DEV_USER_ID <= 0/, 'startup must reject an invalid development user id')
assert.match(appSource, /setAuthTokens\(FASTAPI_DEV_ACCESS_TOKEN\)/, 'startup must persist the configured backend token')
assert.match(appSource, /getAccessToken\(\) != FASTAPI_DEV_ACCESS_TOKEN/, 'startup must verify that the backend token was persisted')
assert.match(appSource, /uni\.setStorageSync\('xsa_user_id', FASTAPI_DEV_USER_ID\)/, 'startup must persist the matching backend user id')
assert.match(appSource, /uni\.switchTab\(\{[\s\S]*?url: '\/pages\/community\/community'/, 'startup must enter the community tab')

// —— 登录态自动续期（2026-10-25）——
assert.match(configSource, /export function getRefreshToken/, 'config must expose the refresh-token reader')
assert.match(requestSource, /\/auth\/refresh/, 'silent renewal must call /auth/refresh')
assert.match(requestSource, /refreshingPromise/, 'renewal must single-flight concurrent 401s')
assert.match(requestSource, /__retried/, 'renewal must retry at most once')
assert.match(authSource, /refreshAccessToken/, 'auth module must expose the renewal entry')

console.log('PASS FastAPI request transport contract')
